#!/usr/bin/env python3
"""Writes include/tokenizer_data.h: the byte-level BPE's byte->codepoint map and
the codepoint classes its pre-tokenizer regexes name (\\p{L}, \\p{M}, \\p{N}, \\s).

  python3.11 -I tools/gen_tokenizer_data.py > include/tokenizer_data.h

The classes come from Python's unicodedata, whose Unicode version is Python's:
the tables are Unicode 14.0 (Python 3.11), and the script refuses another, so
regenerating them is never a silent change of version.
"""
import sys
import unicodedata

UNICODE = "14.0.0"


def bytes_to_unicode():
    """GPT-2's map: printable bytes stand for themselves, the rest from 256 up."""
    bs = list(range(ord("!"), ord("~") + 1)) + list(range(ord("¡"), ord("¬") + 1)) + \
        list(range(ord("®"), ord("ÿ") + 1))
    cs = bs[:]
    n = 0
    for b in range(256):
        if b not in bs:
            bs.append(b)
            cs.append(256 + n)
            n += 1
    return dict(zip(bs, cs))


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def category(c):
    return lambda cp: unicodedata.category(chr(cp))[0] == c


def main():
    if unicodedata.unidata_version != UNICODE:
        sys.exit(f"gen_tokenizer_data: Unicode {unicodedata.unidata_version}, the tables are "
                 f"{UNICODE} (run it with Python 3.11)")
    b2c = bytes_to_unicode()
    print("""#pragma once
// Auto-generated unicode tables for the GPT-2 byte-level BPE tokenizer.
// Generated by tools/gen_tokenizer_data.py from Python 3.11's unicodedata (Unicode
// 14.0: categories L*, M*, N*) + str.isspace() and the GPT-2 bytes_to_unicode() map.
// Consumed by tokenizer.h. Do not hand-edit.
#include <cstdint>
namespace tl::tokdata {
// GPT-2 byte->unicode-codepoint map: byte b (0..255) renders as codepoint
// byte2cp[b]; a token string is a sequence of these codepoints, UTF-8 encoded.
inline constexpr uint32_t byte2cp[256] = {""")
    for row in range(16):
        print("  " + ", ".join(str(b2c[b]) for b in range(row * 16, row * 16 + 16)) + ",")
    print("};")
    print("// Inclusive codepoint ranges for the regex classes \\p{L}, \\p{N}, \\p{M}, \\s.")
    for name, pred in (("L", category("L")), ("N", category("N")), ("M", category("M")),
                       ("WS", lambda cp: chr(cp).isspace())):
        r = ranges(pred)
        print(f"inline constexpr uint32_t range_{name}[][2] = {{"
              + ", ".join(f"{{{a},{b}}}" for a, b in r) + "};")
        print(f"inline constexpr int range_{name}_n = {len(r)};")
    print("""
inline bool in_ranges(uint32_t cp, const uint32_t r[][2], int n) {
  int lo = 0, hi = n - 1;
  while (lo <= hi) { int m = (lo + hi) / 2;
    if (cp < r[m][0]) hi = m - 1; else if (cp > r[m][1]) lo = m + 1; else return true; }
  return false;
}
inline bool is_L(uint32_t cp)  { return in_ranges(cp, range_L,  range_L_n); }
inline bool is_N(uint32_t cp)  { return in_ranges(cp, range_N,  range_N_n); }
inline bool is_M(uint32_t cp)  { return in_ranges(cp, range_M,  range_M_n); }
inline bool is_WS(uint32_t cp) { return in_ranges(cp, range_WS, range_WS_n); }
}  // namespace tl::tokdata""")


if __name__ == "__main__":
    main()
